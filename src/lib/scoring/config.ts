// ---------- Код ----------
//
// Категория считается по самим исходникам из клона (см. git/code-facts.ts),
// а не по косвенным признакам вокруг кода. Прошлые метрики «доля PR с ревью»
// и «медиана времени до первого ревью» убраны: данных по ним у нас нет, они
// всегда были unknown и молча отдавали весь вес двум галочкам из дерева.

// Lock-файл и бот обновлений переехали сюда из «Безопасности»: это гигиена
// сборки, а не результат сканирования. Балл безопасности — только AppSec.
